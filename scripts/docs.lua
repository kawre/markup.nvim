	vim.fn.delete(dir, "rf")
	local template = read(root .. "/scripts/skill.md")
	write(dir .. "/SKILL.md", (template:gsub("{{version}}", version())))
	for name, text in pairs(api) do
		write(dir .. "/reference/" .. name, text)
	end
