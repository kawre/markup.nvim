--- Where the type of a one-line alias ends and its description starts. A
--- space ends the type, unless it is inside brackets or next to a `|` or a `:`,
--- as in `a | b` and `fun(t: number): number`.
local function split_alias(text)
	local depth = 0
	for i = 1, #text do
		local char = text:sub(i, i)
		if char:match("[%(%[{<]") then
			depth = depth + 1
		elseif char:match("[%)%]}>]") then
			depth = depth - 1
		elseif char == " " and depth == 0 then
			local before = text:sub(1, i - 1):match("(%S)%s*$")
			local after = text:sub(i):match("^%s*(%S)")
			if before ~= "|" and before ~= ":" and after ~= "|" then
				return trim(text:sub(1, i - 1)), trim(text:sub(i))
			end
		end
	end
	return trim(text), ""
end

--- An alias as written, read from its source: lua-language-server gives back
--- only its name, as `hover.expandAlias` is off, and drops its description.
--- A union written as `---|` lines keeps one line for each.
---@return string type, string desc
local function alias_source(file, line)
	local lines = vim.split(read(root .. "/lua/" .. file), "\n", { plain = true })
	local rest = lines[line]:match("^%-%-%-@alias%s+%S+%s*(.*)$")
	if not rest then
		return "", ""
	end
	if rest ~= "" then
		return split_alias(rest)
	end
	local union = {}
	for i = line + 1, #lines do
		local option = lines[i]:match("^%-%-%-|%s*(.*)$")
		if not option then
			break
		end
		table.insert(union, "| " .. option)
	end
	return table.concat(union, "\n"), ""
end

--- Classes and aliases of lua/markup, each with what it documents.
---@return docs.class[]
local function lua_classes()
	local classes = {}
	for _, entry in ipairs(export_lua()) do
		local define = entry.defines and entry.defines[1]
		local file = define and define.file
		if
			entry.type == "type"
			and file
			and file:match("^markup/")
			and (entry.name == "Markup" or entry.name:match("^markup"))
			and public(entry.name)
		then
			local class = {
				name = entry.name,
				file = "lua/" .. file,
				desc = "",
				members = {},
			}
			for _, d in ipairs(entry.defines) do
				if d.type == "doc.alias" then
					local alias, desc = alias_source(d.file, d.start[1] + 1)
					class.alias = alias ~= "" and alias or d.view
					if desc ~= "" then
						class.desc = desc
					end
				elseif d.rawdesc and d.rawdesc ~= "" and class.desc == "" then
					class.desc = clean(d.rawdesc)
				end
			end
			local seen = {}
			for _, field in ipairs(entry.fields or {}) do
				local name = field.name
				if
					field.visible == "public"
					and type(name) == "string"
					and public(name)
					and not seen[name]
				then
					seen[name] = true
					local extends = field.extends or {}
					local is_fn = extends.type == "function"
					local kind = field.type == "setmethod" and "method"
						or (is_fn and "function")
						or "field"
					local signature = is_fn and extends.view or field.view or "any"
					-- "(method) markup.view:render(...)" reads as a signature without the tag.
					signature = signature:gsub("^%((%w+)%)%s*", "")
					table.insert(class.members, {
						name = name,
						kind = kind,
						type = signature,
						desc = clean(field.rawdesc or extends.rawdesc),
					})
				end
			end
			-- A class with methods is an object: its fields without a description
			-- are its own state. Without methods it is data, such as props, and
			-- the names of its fields are the API.
			local has_methods = false
			for _, member in ipairs(class.members) do
				has_methods = has_methods or member.kind ~= "field"
			end
			if has_methods then
				class.members = vim.tbl_filter(function(member)
					return member.kind ~= "field" or member.desc ~= ""
				end, class.members)
			end
			table.sort(class.members, function(a, b)
				if (a.kind == "field") ~= (b.kind == "field") then
					return a.kind == "field"
				end
				return a.name < b.name
			end)
			if class.alias or class.desc ~= "" or #class.members > 0 then
				table.insert(classes, class)
			end
		end
	end
	table.sort(classes, function(a, b)
		return a.name:lower() < b.name:lower()
	end)
	return classes
end

local function member_title(class, member)
	if member.kind == "method" then
		return ("%s:%s()"):format(class.name, member.name)
	elseif member.kind == "function" then
		return ("%s.%s()"):format(class.name, member.name)
	end
	return ("%s.%s"):format(class.name, member.name)
end

