-- Writes the documentation from the comments in the code, and the AI skills
-- that carry it. Written for language models first: full signatures, every
-- type spelled out, one topic per file, nothing to skip over.
--
--   llms.txt              where everything is, for agents
--   docs/api/*.md         the Lua API by topic, from the LuaCATS annotations
--   doc/markup.txt        the same as Vim help, for `:help markup`
--   docs/engine.md        the engine, from the `//!` and `///` comments in Rust
--   skills/markup-nvim/   an Agent Skill, the format Claude, Codex and others
--                         read: SKILL.md from scripts/skill.md, and
--                         docs/api/*.md and CHANGELOG.md as reference/
--
--   nvim -l scripts/docs.lua
--
-- The Lua API comes from lua-language-server's `--doc` export: `$LUALS`, then
-- .tests/luals (`make luals`), then the one on PATH. CI pins its version, so
-- what it writes is what gets committed.

local root = vim.fn.getcwd()
local GENERATED = "Generated by scripts/docs.lua from the comments in the code. Do not edit."

local function read(path)
	local file = assert(io.open(path, "rb"))
	local text = file:read("*a")
	file:close()
	return text
end

local function write(path, text)
	vim.fn.mkdir(vim.fs.dirname(path), "p")
	local file = assert(io.open(path, "wb"))
	file:write(text)
	file:close()
end

local function trim(text)
	return (text or ""):gsub("^%s+", ""):gsub("%s+$", "")
end

--- Lines without the space LuaCATS leaves after `---`, as one paragraph block.
--- `@see` comes as a link to a file on the machine that wrote it, with a line
--- number: only the name stays, the same everywhere and as code moves.
local function clean(text)
	text = (text or ""):gsub("%[([^%]]+)%]%(file://[^)]*%)", "`%1`")
	local lines = vim.split(text, "\n", { plain = true })
	for i, line in ipairs(lines) do
		lines[i] = line:gsub("^ ", "")
	end
	return trim(table.concat(lines, "\n"))
end

