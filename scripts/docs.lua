--- The `pub` items of a file with the `///` above them, and its `//!`.
local function rust_file(path)
	local module, items, pending = {}, {}, {}
	local in_tests = false
	local lines = vim.split(read(path), "\n", { plain = true })
	for i, line in ipairs(lines) do
		local inner = line:match("^%s*//!%s?(.*)$")
		local outer = line:match("^%s*///%s?(.*)$")
		if line:match("^#%[cfg%(test%)%]") then
			in_tests = true
		elseif in_tests then
			-- Unit tests run to the end of the file.
		elseif inner then
			table.insert(module, inner)
		elseif outer then
			table.insert(pending, outer)
		elseif line:match("^%s*#%[") then
			-- Attributes sit between a comment and its item.
		else
			local item = trim(line):match("^pub%s.*") or trim(line):match("^pub%(crate%)%s.*")
			if item and #pending > 0 then
				-- The signature, up to where its body starts.
				local signature = item
				local j = i
				while not signature:find("[{;]") and lines[j + 1] and j < i + 8 do
					j = j + 1
					signature = signature .. " " .. trim(lines[j])
				end
				signature = trim(signature:gsub("%s*[{;].*$", ""))
				table.insert(items, { signature = signature, doc = table.concat(pending, "\n") })
			end
			pending = {}
		end
	end
	return trim(table.concat(module, "\n")), items
end

local function rust_markdown()
	local base = "lua/markup/core"
	local files = {}
	for name, kind in vim.fs.dir(base, { depth = math.huge }) do
		if kind == "file" and name:match("%.rs$") then
			table.insert(files, name)
		end
	end
	-- lib.rs first: it says what the crate is.
	table.sort(files, function(a, b)
		if (a == "lib.rs") ~= (b == "lib.rs") then
			return a == "lib.rs"
		end
		return a < b
	end)
	local out = {
		"<!-- " .. GENERATED .. " -->",
		"",
		"# markup.nvim engine",
		"",
		"The native half of markup.nvim, in Rust: the node tree, layout, paint and",
		"the diff that becomes buffer patches. For working on the engine; plugins",
		"use it through the Lua API in [api/](api/README.md).",
	}
	for _, name in ipairs(files) do
		local module, items = rust_file(base .. "/" .. name)
		if module ~= "" or #items > 0 then
			vim.list_extend(out, { "", "## `" .. name .. "`", "", ("*%s/%s*"):format(base, name) })
			if module ~= "" then
				vim.list_extend(out, { "", module })
			end
			for _, item in ipairs(items) do
				vim.list_extend(out, { "", "```rust", item.signature, "```", "", trim(item.doc) })
			end
		end
	end
	return table.concat(out, "\n") .. "\n"
end

