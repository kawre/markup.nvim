-- Lua, through lua-language-server

local function luals()
	if vim.env.LUALS then
		return vim.env.LUALS
	end
	local local_bin = root .. "/.tests/luals/bin/lua-language-server"
	if vim.uv.fs_stat(local_bin) then
		return local_bin
	end
	return "lua-language-server"
end

local function export_lua()
	local out = vim.fn.tempname()
	vim.fn.mkdir(out, "p")
	-- Types as written, `markup.justify` rather than its values, and every value
	-- of an enum rather than the first few.
	local config = out .. "/luarc.json"
	write(config, vim.json.encode({ ["hover.enumsLimit"] = 1000, ["hover.expandAlias"] = false }))
	local result = vim.system({
		luals(),
		"--configpath=" .. config,
		"--doc=" .. root .. "/lua",
		"--doc_out_path=" .. out,
	}):wait()
	local path = out .. "/doc.json"
	if not vim.uv.fs_stat(path) then
		error(
			"lua-language-server wrote no doc.json:\n"
				.. (result.stderr or "")
				.. (result.stdout or "")
		)
	end
	local doc = vim.json.decode(read(path))
	vim.fn.delete(out, "rf")
	return doc
end

