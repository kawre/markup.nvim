-- Vim help

local WIDTH = 78

local used_tags = {}

--- A line with `tag` at its right edge, as help files mark what `:help` finds.
--- A tag is unique in a help file: a name that already has one gets none.
local function tagged(text, tag)
	if used_tags[tag] then
		return text
	end
	used_tags[tag] = true
	local mark = "*" .. tag .. "*"
	local gap = WIDTH - vim.fn.strdisplaywidth(text) - #mark
	if gap < 1 then
		return text .. "\n" .. string.rep(" ", WIDTH - #mark) .. mark
	end
	return text .. string.rep(" ", gap) .. mark
end

--- Markdown code fences as help examples: `>lua` above, `<` below.
local function help_text(text, indent)
	local out, in_code = {}, false
	for _, line in ipairs(vim.split(text, "\n", { plain = true })) do
		local lang = line:match("^%s*```(%w*)")
		if lang and not in_code then
			in_code = true
			table.insert(out, (">" .. (lang ~= "" and lang or "")))
		elseif line:match("^%s*```") and in_code then
			in_code = false
			table.insert(out, "<")
		elseif in_code then
			table.insert(out, "    " .. line)
		else
			table.insert(out, line == "" and "" or indent .. line)
		end
	end
	return out
end

local function vimdoc(classes)
	used_tags = { ["markup.txt"] = true }
	local rule = string.rep("=", WIDTH)
	local out = {
		tagged("*markup.txt*  Reactive user interfaces inside Neovim", "markup.nvim"),
		"",
		GENERATED,
		"",
		rule,
		tagged("CONTENTS", "markup-contents"),
		"",
	}
	for _, class in ipairs(classes) do
		local name = "    " .. class.name
		table.insert(
			out,
			name
				.. string.rep(".", math.max(2, WIDTH - #name - #class.name - 4))
				.. "|"
				.. class.name
				.. "|"
		)
	end
	for _, class in ipairs(classes) do
		vim.list_extend(out, { "", rule, tagged(class.name, class.name), "", "    " .. class.file })
		if class.desc ~= "" then
			table.insert(out, "")
			vim.list_extend(out, help_text(class.desc, ""))
		end
		if class.alias then
			local alias = class.alias:gsub("\n", "\n    " .. (" "):rep(#class.name + 1))
			vim.list_extend(out, { "", ">lua", "    " .. class.name .. " = " .. alias, "<" })
		end
		for _, m in ipairs(class.members) do
			local title = member_title(class, m)
			vim.list_extend(out, { "", tagged(title, title) })
			vim.list_extend(out, help_text(m.type, "    "))
			if m.desc ~= "" then
				vim.list_extend(out, help_text(m.desc, "    "))
			end
		end
	end
	vim.list_extend(out, { "", " vim:tw=78:ts=8:noet:ft=help:norl:" })
	return table.concat(out, "\n") .. "\n"
end

