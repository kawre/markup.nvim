local function class_markdown(class)
	local out = { "## " .. class.name, "", ("Source: `%s`"):format(class.file) }
	if class.desc ~= "" then
		vim.list_extend(out, { "", class.desc })
	end
	if class.alias then
		vim.list_extend(out, {
			"",
			"```lua",
			"---@alias "
				.. class.name
				.. (class.alias:match("^| ") and "\n---" or " ")
				.. (class.alias:gsub("\n", "\n---")),
			"```",
		})
	end
	local fields = vim.tbl_filter(function(m)
		return m.kind == "field"
	end, class.members)
	if #fields > 0 then
		vim.list_extend(out, { "", "Fields:", "" })
		for _, f in ipairs(fields) do
			local line = ("- `%s`: `%s`"):format(f.name, f.type:gsub("\n", " "))
			if f.desc ~= "" then
				line = line .. " - " .. f.desc:gsub("\n+", " ")
			end
			table.insert(out, line)
		end
	end
	for _, m in ipairs(class.members) do
		if m.kind ~= "field" then
			vim.list_extend(
				out,
				{ "", "### " .. member_title(class, m), "", "```lua", m.type, "```" }
			)
			if m.desc ~= "" then
				vim.list_extend(out, { "", m.desc })
			end
		end
	end
	return out
end

--- One file of Markdown for each topic, and the index of them.
---@return table<string, string> files by name, and the index as `README.md`
local function lua_markdown(classes)
	local by_topic = {}
	for _, class in ipairs(classes) do
		local topic = topic_of(class.name)
		by_topic[topic.file] = by_topic[topic.file] or {}
		table.insert(by_topic[topic.file], class)
	end
	local files = {}
	local index = {
		"<!-- " .. GENERATED .. " -->",
		"",
		"# markup.nvim Lua API",
		"",
		"One file per topic. Every class with its fields and functions, the full",
		"signatures and types, from the LuaCATS annotations in `lua/`.",
		"",
	}
	-- Listed in the order to read them, matched in the order of TOPICS.
	local listed = vim.deepcopy(TOPICS)
	table.sort(listed, function(a, b)
		return (READING[a.file] or 99) < (READING[b.file] or 99)
	end)
	for _, topic in ipairs(listed) do
		local list = by_topic[topic.file]
		if list then
			local out = {
				"<!-- " .. GENERATED .. " -->",
				"",
				"# " .. topic.title,
				"",
				topic.about,
			}
			local names = {}
			for _, class in ipairs(list) do
				table.insert(out, "")
				vim.list_extend(out, class_markdown(class))
				table.insert(names, "`" .. class.name .. "`")
			end
			files[topic.file .. ".md"] = table.concat(out, "\n") .. "\n"
			vim.list_extend(index, {
				("- [%s.md](%s.md): %s"):format(topic.file, topic.file, topic.about),
				"  Classes: " .. table.concat(names, ", "),
			})
		end
	end
	files["README.md"] = table.concat(index, "\n") .. "\n"
	return files
end

